// Pure generation logic for the pre-hydration HTML shell.
//
// Lives in lib/ (not tool/) so that both tool/generate_shell.dart and
// test/static_shell_test.dart can import it as a package. No dart:io and no
// Flutter imports — it only turns data into a string.
//
// See tool/generate_shell.dart for the CLI and test/static_shell_test.dart
// for the drift guard.

import 'models/data.dart';

const beginMarker = '  <!-- SHELL:BEGIN — generated by tool/generate_shell.dart. Do not edit by hand. -->';
const endMarker = '  <!-- SHELL:END -->';

const ldBeginMarker = '  <!-- LDJSON:BEGIN — generated by tool/generate_shell.dart. Do not edit by hand. -->';
const ldEndMarker = '  <!-- LDJSON:END -->';

const llmsBeginMarker = '<!-- LINKS:BEGIN generated -->';
const llmsEndMarker = '<!-- LINKS:END -->';

String esc(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

/// Strips the leading "Stack & Architecture: " label and the trailing
/// sentence(s), leaving just the comma-separated stack for the shell.
String stackLine(Map<String, dynamic> p) {
  final raw = (p['architecture'] as String?) ?? '';
  if (raw.isEmpty) return '';
  var s = raw.replaceFirst(RegExp(r'^Stack & Architecture:\s*'), '');
  final dot = s.indexOf('. ');
  if (dot > 0) s = s.substring(0, dot);
  return s.replaceAll(RegExp(r'\.$'), '');
}

String projectBlock(Map<String, dynamic> p) {
  final b = StringBuffer();
  final site = p['website'] as String?;
  b.writeln('      <h3>${esc(p['title'] as String)}</h3>');
  b.writeln('      <p class="role">${esc(p['role'] as String)}</p>');
  b.writeln('      <p>${esc(p['outcome'] as String)}</p>');

  final achievements = (p['achievements'] as List?)?.cast<String>() ?? const [];
  if (achievements.isNotEmpty) {
    b.writeln('      <ul>');
    for (final a in achievements) {
      b.writeln('        <li>${esc(a)}</li>');
    }
    b.writeln('      </ul>');
  }

  final stack = stackLine(p);
  if (stack.isNotEmpty || site != null) {
    b.write('      <p class="stack">');
    if (stack.isNotEmpty) b.write(esc(stack));
    if (site != null) {
      final label = site.replaceFirst(RegExp(r'^https?://(www\.)?'), '')
          .replaceAll(RegExp(r'/$'), '');
      if (stack.isNotEmpty) b.write(' — ');
      b.write('<a href="${esc(site)}">${esc(label)}</a>');
    }
    b.writeln('</p>');
  }

  final download = p['download'] as String?;
  if (download != null) {
    final info = p['downloadInfo'] as String?;
    b.writeln('      <p class="stack"><a href="${esc(download)}">Download for Android</a>'
        '${info == null ? '' : ' — ${esc(info)}'}</p>');
  }
  return b.toString();
}

String buildShell() {
  final b = StringBuffer();
  b.writeln(beginMarker);
  b.writeln('  <div id="shell">');
  b.writeln('    <div class="shell-inner">');
  b.writeln('      <p class="shell-note" id="shell-note">Loading the interactive version…</p>');
  b.writeln('      <h1>${esc(fullName)}</h1>');
  b.writeln('      <p class="role">${esc(siteTagline)}</p>');
  b.writeln('      <p>${esc(bioParagraph)}</p>');

  b.writeln();
  b.writeln('      <h2>Production systems</h2>');
  b.writeln('      <p class="lede">Live platforms with real users, running on infrastructure I provision and maintain myself.</p>');
  for (final p in productionProjects) {
    b.writeln();
    b.write(projectBlock(p));
  }

  b.writeln();
  b.writeln('      <h2>Other projects</h2>');
  b.writeln('      <p class="lede">Product, academic, and personal work. Not production systems I operate.</p>');
  for (final p in otherProjects) {
    b.writeln();
    b.write(projectBlock(p));
  }

  b.writeln();
  b.writeln('      <h2>Skills</h2>');
  for (final g in skillGroups) {
    final skills = (g['skills'] as List).cast<String>();
    b.writeln('      <p><strong>${esc(g['title'] as String)}:</strong> ${esc(skills.join(', '))}</p>');
  }

  b.writeln();
  b.writeln('      <h2>Education &amp; training</h2>');
  for (final e in educationData) {
    final date = e['date'] == 'Completed' ? '' : ' — ${esc(e['date']!)}';
    b.writeln('      <p>${esc(e['title']!)} — ${esc(e['place']!)}$date</p>');
  }

  b.writeln();
  b.writeln('      <h2>Contact</h2>');
  b.writeln('      <p>Email: <a href="mailto:${esc(contactEmail)}">${esc(contactEmail)}</a></p>');
  for (final l in profileLinks) {
    final label = l['url']!.replaceFirst(RegExp(r'^https?://(www\.)?'), '');
    b.writeln('      <p>${esc(l['label']!)}: <a href="${esc(l['url']!)}">${esc(label)}</a></p>');
  }
  b.writeln('      <p>Résumé: <a href="cv.pdf">Download résumé (PDF)</a></p>');

  b.writeln('    </div>');
  b.writeln('  </div>');
  b.write(endMarker);
  return b.toString();
}

/// Escapes a value for embedding in the JSON-LD string literals below.
String jsonEsc(String v) => v
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\n', ' ');

/// Person + one entry per production system, derived from the same data the
/// app renders. Keeps profile URLs and project descriptions defined once.
String buildJsonLd() {
  final b = StringBuffer();
  b.writeln(ldBeginMarker);
  b.writeln('  <script type="application/ld+json">');
  b.writeln('  {');
  b.writeln('    "@context": "https://schema.org",');
  b.writeln('    "@graph": [');
  b.writeln('      {');
  b.writeln('        "@type": "Person",');
  b.writeln('        "@id": "$siteUrl#person",');
  b.writeln('        "name": "${jsonEsc(fullName)}",');
  b.writeln('        "alternateName": "Khader Hwaijeh",');
  b.writeln('        "jobTitle": "Full-Stack Software Engineer",');
  b.writeln('        "description": "${jsonEsc(bioParagraph)}",');
  b.writeln('        "url": "$siteUrl",');
  b.writeln('        "email": "$emailUrl",');
  b.writeln('        "image": "${siteUrl}og-image.jpg",');
  b.writeln('        "address": {');
  b.writeln('          "@type": "PostalAddress",');
  b.writeln('          "addressLocality": "Damascus",');
  b.writeln('          "addressCountry": "SY"');
  b.writeln('        },');
  b.writeln('        "alumniOf": {');
  b.writeln('          "@type": "CollegeOrUniversity",');
  b.writeln('          "name": "Yarmouk Private University"');
  b.writeln('        },');
  b.writeln('        "knowsLanguage": ["ar", "en"],');
  final knows = <String>[
    for (final g in skillGroups) ...(g['skills'] as List).cast<String>(),
  ];
  b.writeln('        "knowsAbout": [');
  for (var i = 0; i < knows.length; i++) {
    final comma = i == knows.length - 1 ? '' : ',';
    b.writeln('          "${jsonEsc(knows[i])}"$comma');
  }
  b.writeln('        ],');
  b.writeln('        "sameAs": [');
  b.writeln('          "$githubUrl",');
  b.writeln('          "$linkedInUrl"');
  b.writeln('        ]');
  b.write('      }');

  for (final p in productionProjects) {
    final type = p['schemaType'] as String? ?? 'CreativeWork';
    final name = (p['schemaName'] ?? p['title']) as String;
    final desc = '${p['outcome']} ${stackLine(p)}.';
    b.writeln(',');
    b.writeln('      {');
    b.writeln('        "@type": "$type",');
    b.writeln('        "name": "${jsonEsc(name)}",');
    b.writeln('        "url": "${p['website'] ?? p['page'] ?? p['download']}",');
    if (p['download'] != null) {
      b.writeln('        "downloadUrl": "${p['download']}",');
    }
    if (type == 'SoftwareApplication') {
      b.writeln('        "applicationCategory": "${p['applicationCategory'] ?? 'BusinessApplication'}",');
      b.writeln('        "operatingSystem": "${p['operatingSystem'] ?? 'Web'}",');
    }
    b.writeln('        "description": "${jsonEsc(desc)}",');
    b.writeln('        "author": { "@id": "$siteUrl#person" }');
    b.write('      }');
  }

  b.writeln();
  b.writeln('    ]');
  b.writeln('  }');
  b.writeln('  </script>');
  b.write(ldEndMarker);
  return b.toString();
}

/// The identity block at the top of llms.txt.
String buildLlmsLinks() {
  final b = StringBuffer();
  b.writeln(llmsBeginMarker);
  b.writeln('- **Site:** $siteUrl');
  b.writeln('- **Email:** $contactEmail');
  for (final l in profileLinks) {
    b.writeln('- **${l['label']}:** ${l['url']}');
  }
  b.writeln('- **Résumé (PDF):** ${siteUrl}cv.pdf');
  b.write(llmsEndMarker);
  return b.toString();
}

String _replaceRegion(String text, String begin, String end, String body) {
  final s = text.indexOf(begin);
  final e = text.indexOf(end);
  if (s < 0 || e < 0) {
    throw StateError('Markers $begin / $end not found.');
  }
  return text.replaceRange(s, e + end.length, body);
}

/// Collapses CRLF to LF so comparisons don't depend on git's autocrlf
/// setting. Without this the drift check fails spuriously on Windows
/// checkouts and in CI.
String normalizeEol(String s) => s.replaceAll('\r\n', '\n');

/// Replaces the marked region of [html] with freshly generated shell markup.
/// Returns LF-normalised output, so compare it against [normalizeEol] input.
String applyTo(String html) {
  var text = normalizeEol(html);
  text = _replaceRegion(text, ldBeginMarker, ldEndMarker, buildJsonLd());
  text = _replaceRegion(text, beginMarker, endMarker, buildShell());
  return text;
}

/// Rewrites the generated identity block inside llms.txt.
String applyToLlms(String llms) => _replaceRegion(
      normalizeEol(llms), llmsBeginMarker, llmsEndMarker, buildLlmsLinks());

bool llmsIsUpToDate(String llms) => applyToLlms(llms) == normalizeEol(llms);

/// True when the shell embedded in [html] is already up to date.
bool isUpToDate(String html) => applyTo(html) == normalizeEol(html);
